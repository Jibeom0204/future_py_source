# 실습 - 적합도 검정(일원 카이제곱 검정)
# 카이제곱 검정의 정식 명칭은 "Pearson's chi-square test"
# 두 개의 불연속변수(범주형)간의 상관관계를 측정. 관찰빈도가 통계적으로 유의한지 확인

# 가설 채택하는 두가지 방법
import pandas as pd


# 공부 여부와 합격 여부 사이에 견관성이 있는가?
# 공부함(범주형), 공부안함(범주형)
data=pd.read_csv("pass_cross.csv",encoding="euc-kr")
# print("csv data 출력:\n",data,'\n')
print(data.head())
print(data.shape,'\n')

# 귀무가설(H0): 벼락치기 공부하는 것과 합격 여부는 관계가 없다.
# 대리가설(H1): 벼락치기 공부하는 것과 합격 여부는 관계가 있다.
print("공부하고 합격",data[(data['공부함']==1) & (data['합격']==1)].shape[0])
print("공부하고 불합격",data[(data['공부함']==1) & (data['불합격']==1)].shape[0])

print("========빈도표========\n")
ctab=pd.crosstab(index=data['공부안함'], columns=data['불합격'], margins=True)
ctab.columns=['합격','불합격','행합']
ctab.index=['공부함','공부안함','열합']
print("ctab 출력",ctab,'\n') # 관찰값(빈도)

# 기대도수 =(각행의 주변 합)*(각 열의 주변 합)/ 총합(전체 표본 수)
chi2 = ((18-15)**2/15 + (7-10)**2/10 + (12-15)**2/15 + (13-10)**2/10)
print("검정 통계량 chi2: ",chi2,'\n') #3.0

#df= 2-1=1
# 유의 수준 a = 0.05
# 임계값(critical value) - H0를 기각할 지 결정하는 값 : 3.84(카이제곱 분포표 참고함)
# 판정: 검정 통계량 chi2:  3.0이 임계값인 3.84보다 작으므로 귀무 채택력 내에 존재하여 귀무가설 채택

print("==========방법 2: P-value 사용==========")
import scipy.stats as stats
observed=ctab.iloc[:2,:2] # 합계는 제외함
chi2, p, _, _ =stats.chi2_contingency(observed,correction=False)
print("검정통계량 ",chi2) #검정통계량  3.0
print("유의 확률(p값) ",p) #유의 확률(p값)  0.5578254003710748
# 판정: 유의수준 0.05<p:0.5578254이므로 귀무가설 채택
# 검정에 사용된 자료는 우연히 발생한 자료라고 할 수 있다.

# 유의 수준 5%에서 유의한 연관서잉 있다고 판단하기에느 증거가 충붆지 않다.

# 참고: p-value가 0.05보다 크다고 해서 귀무가설ㅇ 옳다는 뜻은 아니다. 확정 아님!
# 현재 데이터만으로 귀무가서릉 기각할 만큼 충분한 통계적 근거가 없다는 뜻이다. 약간은 모호함