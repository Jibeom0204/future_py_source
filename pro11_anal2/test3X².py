# 주사위를 60회 던져서 나온 관측도수/기대도수가 아래와 같이 나온 경우에
# 이 주사위는 일반적인 게임에 적합한 주사위가 맞는가를 일원카이제곱 검정으로 분석하자


# 귀무가설: 기대치와 관찰치는 차이가 없음
# 대립가설: 기대치와 관찰치는 차이가 있음. 이 주사위는 게임에 적합하지 않음

import pandas as pd
import scipy.stats as stats

data=[4,6,17,16,8,9]
print("ㅇㅇ?",stats.chisquare(data)) # Power_divergenceResult(statistic=np.float64(14.200000000000001), pvalue=np.float64(0.014387678176921308))
result=stats.chisquare(data)
print(f"카이제곱 검정통계량:{result.statistic:.4f}")
print(f"유의확률(P value):{result.pvalue:.4f}")

# 프로그래밍하듯 적고 싶으면
alpha=0.05
if result.pvalue<alpha:
    print("판정: 귀무가설 기각: 통계적 유의함")
else:
    print("판정: 귀무가설 채택: 통계적 유의성을 가지지 않음")
# 판정: 유의수준 0.05> pvalue 0.0144이므로 귀무가설을  기각하고 대립가설을 채택
# 검정에 사용된 데이터는 우연히 발생한 것이 아니라 필연적인 원인에 의해 발생한 것이다.
