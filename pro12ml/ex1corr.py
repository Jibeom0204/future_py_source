"""
분산(Varience): 한개의 변수가 평균으로부터 얼마나 흩어져 있는지
공분산(Covarience): 빌 공자 아님. 이바지할 공 임/// 두개의 변수가 함께 어떻게 변하는지 확인
 -> 두 변수가 각가의 평균을 기준으로 함꼐 증가하거나 함께 감소하는 경햐잉 있는지 나타내는 통계량
  계산: 각 관측값이 평균보다 높은지 낮은지를 비교하여 두 편차의 곱을 계산
  변수가 두개인 경우는 분산을 방향
"""

import numpy as np

# 공분산
print("변수 1: ",np.arange(1,6))
print("변수 2: ",np.arange(2,7),'\n')
print("변수 1,2, 공분산\n",np.cov(np.arange(1,6),np.arange(2,7))) #공분산이니까 값 2개 넣어주기
# 변수 1,2, 공분산
#  [[2.5 2.5]
#  [2.5 2.5]]
# 대각선 우상향값은 공분산. 1행 1열, 2행 2열 값은 변수1,변수2에 해당하는 개별 분산 값


print("변수 3,4, 공분산\n",np.cov(np.arange(10,60,10),np.arange(20,70,10))) 
# 변수 3,4, 공분산
#  [[250. 250.]
#  [250. 250.]]

print("변수 5,6, 공분산\n",np.cov(np.arange(1,6,1),(3,3,3,3,3))) # 수평선. x가 증가하는 값에 따라 y의 변화가 없음
# 변수 5,6, 공분산
#  [[2.5 0. ]
#  [0.  0. ]]

print("변수 7,8, 공분산\n",np.cov(np.arange(1,6,1),np.arange(6,1,-1))) #-2.5 우하향
# 변수 7,8, 공분산
#  [[ 2.5 -2.5]
#  [-2.5  2.5]]

print("변수 9,10, 공분산\n",np.cov(np.arange(1,6,1),np.arange(7,17,2))) # 5 우상향. 변수9 분산=2.5 // 변수10 분산=10
# 변수 9,10, 공분산
#  [[ 2.5  5. ]
#  [ 5.  10. ]]

print("변수 11,12, 공분산\n",np.cov(np.arange(100,600,100),np.arange(200,700,100)))
# 변수 11,12, 공분산
#  [[25000. 25000.]
#  [25000. 25000.]]

# 두 변수 사이의 선형관계 방향(좌/우 상/하향)은 알 수 있으나 강도를 알 수 없다
print()


# 상관 계수: 공분산을 표준화한 값 => 공분산을 두 변수의 표준편차 곱으로 나눈 값
#           => 두 변수의 측정단위나 크기에 상관없이 -1~1 사이의 값으로 표현가능
x=[8,3,6,6,9,4,3,9,3,4]
print('x 평균: ',np.mean(x))
print('x 분산: ',np.var(x))

y=[6,2,4,6,9,5,1,8,4,5]
print('y 평균: ',np.mean(x))
print('y 평균: ',np.var(x),'\n')

import matplotlib.pyplot as plt
plt.plot(x,y,'o')
plt.show()

#print('x,y의 공분산:', np.cov(x,y)) #5.22222222]
print('x,y의 공분산:', np.cov(x,y)[0,1],'\n')# x,y의 공분산만 출력: 5.222. 두 변수는 양의 상관관계

x2=[80,30,60,60,90,40,30,90,30,40]
y2=[60,20,40,60,90,50,10,80,40,50]
print('x2,y2의 공분산:', np.cov(x2,y2)[0,1],'\n')  # x2,y2의 공분산: 522.222
plt.plot(x2,y2,'o')
plt.show()

# 패턴이 일치할지라도 두 데이터의 단위에 따라 공분산의 크기가 달라지므로 절대적 크기 판단이 어려움
# 공분산을 표준화햇 -1~0~1 범이로 만든 것이 상관계수(r) 
print("x,y의 상관계수: \n",np.corrcoef(x,y)[0,1],'\n')
print("x2,y2의 상관계수: \n",np.corrcoef(x2,y2)[0,1],'\n')
# x,y의 상관계수: 
#  0.8663686463212855 

# x2,y2의 상관계수: 
#  0.8663686463212852 
print("x2,y의 상관계수: \n",np.corrcoef(x2,y)[0,1],'\n')
# x2,y의 상관계수: 
#  0.8663686463212853 


# 피어슨 상관계수: 두 연속형 변수 간의 선형상관
# 범위 -1~1
# 1: 완벽한 양의 상관관계 -1: 완벽한 음의 상관관계  0: 선형상관관계 없음
# 주의: 상관 관계가 높다고 반드시 인과관계를 가지는 것은 아님

from scipy import stats
print("scipy 모듈 사용 피어슨상관계수 r: ",stats.pearsonr(x,y)) # statistic=np.float64(0.8663. 위의 상관계수와 동일
print("scipy 모듈 사용 스피어만상관계수 r: ",stats.spearmanr(x,y))

print("===비 선형 데이터인 경우 공분산, 상관계수는 의미가 조또 없음===") # 1차함수 같은 것만 됨
m=[-3,-2,-1,0,1,2,3]
n=[9,4,1,0,1,4,9]
plt.plot(m,n,'o')
plt.show()

print(np.cov(m,n)[0,1]) # 0.0
print(np.corrcoef(m,n)[0,1]) # 0.0